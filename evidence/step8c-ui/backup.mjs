import fs from 'node:fs';
import { db } from '../../server/src/db.js';
import { readInitialSync } from '../../server/src/utils/initialSyncStore.js';
const conn = db.prepare("SELECT id, full_sync_json, initial_sync_json, status, remote_user_id FROM tracker_connections WHERE provider='simkl'").get();
const job = readInitialSync();
const hdr = db.prepare("SELECT data FROM settings WHERE id='initial-outward-sync'").get();
const items = db.prepare("SELECT * FROM initial_sync_items").all();
const runs = db.prepare("SELECT id,status FROM simkl_full_sync_runs").all();
fs.writeFileSync('evidence/step8c-ui/original.json', JSON.stringify({ conn, hdr, items, runs }, null, 1));
console.log(JSON.stringify({ conn, jobStatus: job?.status, dests: job?.destinations?.map(d => [d.provider, d.status, d.items.length]), itemsTotal: items.length, runs }, null, 1));
process.exit(0);
