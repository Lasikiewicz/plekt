import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { checkCodeIndex } from "../scripts/docs-check.js";
import { extractExports, extractRoutes, generateCodeIndex } from "../scripts/generate-code-index.js";

const fixture = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "fixtures", "code-index");

function copyFixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "code-index-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  fs.cpSync(fixture, dir, { recursive: true });
  return dir;
}

test("routes cover plain paths, || chains, regex, startsWith and includes, sorted by path", () => {
  const source = fs.readFileSync(path.join(fixture, "server/src/index.js"), "utf8");
  const routes = extractRoutes(source, "server/src/index.js");
  assert.deepEqual(routes, [
    { patterns: ["`/^alpha\\/[a-z]+(?:\\/status|\\/server)?$/i`"], handler: "handleList", file: "server/src/routes/alpha.js" },
    { patterns: ["`alpha`", "`alpha-old`"], handler: "handleAlpha", file: "server/src/routes/alpha.js" },
    { patterns: ["`beta/one`", "`beta/two`"], handler: "handleBeta", file: "server/src/routes/beta.js" },
    { patterns: ["`gamma`", "`startsWith(\"gamma/\")`"], handler: "handleGamma", file: "server/src/routes/beta.js" },
    { patterns: ["`local`"], handler: "handleLocal", file: "server/src/index.js" },
    { patterns: ["`zeta`"], handler: "handleBeta", file: "server/src/routes/beta.js" },
  ]);
});

test("exports cover declarations, export lists, aliases and re-exports, sorted", () => {
  assert.deepEqual(
    extractExports(fs.readFileSync(path.join(fixture, "server/src/routes/beta.js"), "utf8")),
    ["* from ./alpha.js", "handleBeta", "handleGamma", "renamedExport"],
  );
  assert.deepEqual(
    extractExports(fs.readFileSync(path.join(fixture, "server/src/routes/alpha.js"), "utf8")),
    ["ALPHA_LIMIT", "handleAlpha", "handleAlphaList"],
  );
  assert.deepEqual(
    extractExports(fs.readFileSync(path.join(fixture, "public/modules/widget.js"), "utf8")),
    ["Widget", "aliasedThing", "counter", "ids", "thing"],
  );
});

test("generated index groups modules by directory, caps long rows and has no line numbers", () => {
  const output = generateCodeIndex({ rootDir: fixture });
  assert.match(output, /^# Code index\n\nGenerated by `npm run code-index`\. Do not edit by hand\./);
  assert.match(output, /\| `alpha`, `alpha-old` \| `handleAlpha` \| `routes\/alpha\.js` \|/);
  assert.match(output, /\| `local` \| `handleLocal` \| `index\.js` \|/);
  assert.match(output, /\| `\/\^alpha\\\/\[a-z\]\+\(\?:\\\/status\\\|\\\/server\)\?\$\/i` \|/, "regex pipes are escaped for the table");
  const headings = [...output.matchAll(/^### (.+)$/gm)].map((match) => match[1]);
  assert.deepEqual(headings, ["public/modules/", "server/src/", "server/src/routes/"]);
  assert.match(output, /- `many\.js`: a, b, c, d, e, f, g, h and 2 more\n- `widget\.js`:/);
  assert.match(output, /- `index\.js`: dispatch\n/);
  assert.doesNotMatch(output, /:\d+\b(?![^`]*`)/, "no file:line references");
});

test("generator output is deterministic and skips test files and node_modules", (t) => {
  const dir = copyFixture(t);
  const before = generateCodeIndex({ rootDir: dir });
  fs.writeFileSync(path.join(dir, "server/src/routes/beta.test.js"), "export function skippedTest() {}\n");
  fs.mkdirSync(path.join(dir, "public/modules/node_modules/pkg"), { recursive: true });
  fs.writeFileSync(path.join(dir, "public/modules/node_modules/pkg/index.js"), "export function skippedDependency() {}\n");
  const after = generateCodeIndex({ rootDir: dir });
  assert.equal(after, before);
  assert.equal(generateCodeIndex({ rootDir: dir }), after);
});

test("code index check fails on a renamed export and passes on edits that only move lines", (t) => {
  const dir = copyFixture(t);
  fs.mkdirSync(path.join(dir, "docs"));
  fs.writeFileSync(path.join(dir, "docs/code-index.md"), generateCodeIndex({ rootDir: dir }));
  assert.deepEqual(checkCodeIndex({ rootDir: dir }), []);

  const alpha = path.join(dir, "server/src/routes/alpha.js");
  const original = fs.readFileSync(alpha, "utf8");
  fs.writeFileSync(alpha, `\n\n${original}\n// trailing comment\n`);
  assert.deepEqual(checkCodeIndex({ rootDir: dir }), [], "moving lines does not make the index stale");

  fs.writeFileSync(alpha, original.replace("handleAlphaList", "handleAlphaIndex"));
  const failures = checkCodeIndex({ rootDir: dir });
  assert.equal(failures.length, 1);
  assert.match(failures[0], /out of date.*npm run code-index/);
});

test("code index check reports a missing index", (t) => {
  const dir = copyFixture(t);
  assert.match(checkCodeIndex({ rootDir: dir }).join("\n"), /missing - run `npm run code-index`/);
});
