import fs from "node:fs/promises";
import path from "node:path";
import { getDataVersion, getUpNextVersion, bumpUpNextVersion } from "../db.js";
import { DATA_DIR } from "../paths.js";
import { getUpNextFeedSourceVersion, listUpNextProviderFeedStates } from "./upNextRepository.js";
import { getCanonicalPosterUrl } from "./mediaArtwork.js";
import { publicUpNextItems } from "./upNextService.js";
import { sortUpNextItems } from "./upNextIdentity.js";

// Bump when the projection's episode-order rules change so a persisted queue
// built by the previous rule cannot keep showing a later-season episode.
const CACHE_VERSION = 6;
const CACHE_FILE = path.join(DATA_DIR, "up-next-cache.json");
const TEMP_FILE = `${CACHE_FILE}.${process.pid}.tmp`;
const UP_NEXT_TTL_MS = 2 * 60 * 1000;
const REVALIDATE_MIN_INTERVAL_MS = 10 * 60 * 1000;
const MAX_ITEMS = 100;
const UP_NEXT_PROVIDERS = new Set(["plex", "emby", "jellyfin"]);

let memoryCache = null;
let memoryMtimeMs = 0;
let writeChain = Promise.resolve();
let buildInFlight = null;
let buildInFlightVersion = 0;
let lastRevalidateAt = 0;

function queueAutomaticUpNextSync(reason) {
  void import("./upNextAutoSync.js")
    .then(({ requestUpNextAutoSync }) => requestUpNextAutoSync(reason))
    .catch((error) => console.error(`[up-next] Automatic sync request failed: ${error?.message || error}`));
}

function emptyCache() {
  return {
    version: CACHE_VERSION,
    builtAt: 0,
    sourceVersion: "",
    historyVersion: getDataVersion(),
    upNextVersion: getUpNextVersion(),
    items: [],
    sourceStatus: [],
  };
}

function normalizeCache(parsed) {
  if (Number(parsed?.version || 0) !== CACHE_VERSION) return emptyCache();
  const rawItems = Array.isArray(parsed?.items) ? parsed.items.slice(0, MAX_ITEMS) : [];
  // Only the episode identity repair is needed for the current regression.
  // Leave legacy movie/unknown rows byte-for-byte compatible until their next
  // normal projection refresh, since older movie ids were not always keys
  // generated by upNextIdentity.js.
  const mergeableItems = rawItems.filter((item) => item?.media_type === "episode");
  const passthroughItems = rawItems.filter((item) => item?.media_type !== "episode").map((item) => {
    const providerItems = Object.fromEntries(Object.entries(item?.provider_items || item?.providerItems || {})
      .map(([provider, ids]) => [String(provider || "").toLowerCase(), ids])
      .filter(([provider, ids]) => UP_NEXT_PROVIDERS.has(provider) && (Array.isArray(ids) ? ids.length : Boolean(ids))));
    const sanitized = { ...item, provider_items: providerItems, providerItems };
    if (sanitized?.media_type === "movie" && !sanitized.poster_url) {
      const canonical = getCanonicalPosterUrl({
        media_type: "movie",
        title: sanitized.title,
        tmdb_id: sanitized.tmdb_id,
        imdb_id: sanitized.imdb_id,
      });
      return canonical ? { ...sanitized, poster_url: canonical } : sanitized;
    }
    return sanitized;
  });
  return {
    version: CACHE_VERSION,
    builtAt: Number(parsed?.builtAt || 0),
    sourceVersion: String(parsed?.sourceVersion || ""),
    historyVersion: Number(parsed?.historyVersion || 0),
    upNextVersion: Number(parsed?.upNextVersion || getUpNextVersion()),
    // Older cache snapshots can contain the same resume twice under an
    // identity-bearing key and a title-only key. Normalize known media rows
    // while leaving legacy/diagnostic entries untouched. Re-sort with the
    // projection's own rule: appending the movies after the episodes moved a
    // part-watched movie to the end of the rail on every cached read.
    items: sortUpNextItems([...publicUpNextItems(mergeableItems), ...passthroughItems]).slice(0, MAX_ITEMS),
    sourceStatus: (Array.isArray(parsed?.sourceStatus) ? parsed.sourceStatus : [])
      .filter((feed) => UP_NEXT_PROVIDERS.has(String(feed?.provider || "").toLowerCase())),
  };
}

async function readCache() {
  try {
    const stat = await fs.stat(CACHE_FILE);
    if (memoryCache && memoryMtimeMs === stat.mtimeMs) return memoryCache;
    const parsed = JSON.parse(await fs.readFile(CACHE_FILE, "utf8"));
    memoryCache = normalizeCache(parsed);
    memoryMtimeMs = stat.mtimeMs;
    return memoryCache;
  } catch (error) {
    if (error?.code !== "ENOENT") console.error("Failed to read Up Next cache", error);
    memoryCache = emptyCache();
    memoryMtimeMs = 0;
    return memoryCache;
  }
}

function normalizedItems(items) {
  return (Array.isArray(items) ? items : []).slice(0, MAX_ITEMS);
}

function comparableSourceStatus(status = []) {
  return (Array.isArray(status) ? status : []).map((feed) => ({
    provider: feed.provider,
    feed_kind: feed.feed_kind,
    status: feed.status,
    item_count: feed.item_count,
    complete: feed.complete,
    last_error: feed.last_error,
  }));
}

async function storeCache(result, fallbackSourceVersion) {
  const projection = result && !Array.isArray(result) && typeof result === "object"
    ? result
    : { items: result };
  const nextItems = normalizedItems(projection.items);
  let stored;
  writeChain = writeChain.catch(() => {}).then(async () => {
    const current = await readCache();
    const nextSourceStatus = Array.isArray(projection.sourceStatus) ? projection.sourceStatus : [];
    const changed = !current.builtAt
      || JSON.stringify({ items: current.items, sourceStatus: comparableSourceStatus(current.sourceStatus) })
        !== JSON.stringify({ items: nextItems, sourceStatus: comparableSourceStatus(nextSourceStatus) });
    const currentGlobalVersion = getUpNextVersion();
    const cachedVersion = Number(current.upNextVersion || 0);
    const historyVersion = getDataVersion();
    const upNextVersion = changed
      ? (currentGlobalVersion > cachedVersion ? currentGlobalVersion : bumpUpNextVersion())
      : Math.max(cachedVersion || 1, currentGlobalVersion);
    const now = Date.now();
    const next = {
      version: CACHE_VERSION,
      builtAt: now,
      sourceVersion: String(projection.sourceVersion || fallbackSourceVersion || getUpNextFeedSourceVersion()),
      historyVersion,
      upNextVersion,
      items: nextItems,
      sourceStatus: nextSourceStatus,
    };
    await fs.mkdir(DATA_DIR, { recursive: true });
    await fs.writeFile(TEMP_FILE, JSON.stringify(next), "utf8");
    await fs.rename(TEMP_FILE, CACHE_FILE);
    // Keep serving exactly what was built. Forcing a re-read ran our own write
    // back through normalizeCache, so the next rebuild never compared equal and
    // every rebuild bumped the Up Next version. Another process's later write
    // still changes the mtime and is picked up.
    memoryCache = next;
    memoryMtimeMs = await fs.stat(CACHE_FILE).then((stat) => stat.mtimeMs, () => 0);
    stored = { ...next, changed };
  });
  await writeChain;
  if (stored?.changed) queueAutomaticUpNextSync("Up Next projection changed");
  return stored;
}

function buildAndStore(build) {
  const requestedVersion = getUpNextVersion();
  if (buildInFlight) {
    // A manual queue change can arrive while a projection is already being
    // built. Do not let the caller receive that older projection and stamp it
    // as current; wait for it to finish, then build against the new queue
    // generation.
    if (buildInFlightVersion !== requestedVersion) {
      return buildInFlight.then(() => buildAndStore(build));
    }
    return buildInFlight;
  }
  buildInFlightVersion = requestedVersion;
  buildInFlight = Promise.resolve()
    .then(() => build())
    .then((result) => storeCache(result, getUpNextFeedSourceVersion()))
    .finally(() => {
      buildInFlight = null;
      buildInFlightVersion = 0;
    });
  return buildInFlight;
}

// Complete an explicit queue mutation before acknowledging it to another device.
// Provider feed refreshes remain background work; this projects canonical state.
export async function refreshUpNextAfterMutation(mediaConfig, reason) {
  const { invalidateHistoryDerivedCaches } = await import("./dataRepo.js");
  const { buildUpNextProjection } = await import("./upNextService.js");
  await invalidateHistoryDerivedCaches(reason);
  return buildAndStore(() => buildUpNextProjection({ mediaConfig }));
}

function publicSnapshot(cache, stale = false, sourceStatus = cache.sourceStatus) {
  return {
    items: cache.items,
    builtAt: cache.builtAt,
    historyVersion: cache.historyVersion,
    upNextVersion: cache.upNextVersion,
    sourceVersion: cache.sourceVersion,
    sourceStatus,
    stale,
  };
}

function currentPublicSourceStatus() {
  return listUpNextProviderFeedStates()
    .filter((feed) => UP_NEXT_PROVIDERS.has(String(feed?.provider || "").toLowerCase()))
    .map((feed) => {
      const publicFeed = { ...feed };
      delete publicFeed.cursor;
      return publicFeed;
    });
}

// `force` skips the provider-feed throttle. It is used when the served snapshot
// predates the latest watch history, where a rebuild must always follow.
function queueBackgroundRebuild(build, { force = false } = {}) {
  if (!force && Date.now() - lastRevalidateAt < REVALIDATE_MIN_INTERVAL_MS) return false;
  lastRevalidateAt = Date.now();
  // Start on a later timer turn rather than a promise microtask. A stale
  // dashboard response should finish before the provider-backed projection
  // can begin its synchronous cache assembly and compete with sibling APIs.
  const timer = setTimeout(() => {
    buildAndStore(build)
      .then((result) => {
        console.log(`Up Next cache background rebuild complete: ${result.items.length} item${result.items.length === 1 ? "" : "s"}${result.changed ? ", cache updated" : ", unchanged"}.`);
      })
      .catch((error) => {
        console.warn(`Up Next cache background rebuild failed: ${error.message}`);
      });
  }, 0);
  timer.unref?.();
  return true;
}

// Return a warm snapshot immediately when possible. `revalidate` is used by
// the dashboard: stale data remains visible while one deduplicated rebuild
// runs behind the request. Explicit `refresh` keeps the existing manual retry
// semantics and waits for a fresh snapshot.
export async function getUpNextCacheSnapshot(build, {
  refresh = false,
  revalidate = false,
  allowStale = false,
} = {}) {
  if (refresh) return publicSnapshot(await buildAndStore(build));

  const cache = await readCache();
  if (!cache.builtAt) {
    if (allowStale) {
      queueBackgroundRebuild(build, { force: true });
      return publicSnapshot(cache, true, currentPublicSourceStatus());
    }
    return publicSnapshot(await buildAndStore(build));
  }

  const sourceVersion = getUpNextFeedSourceVersion();
  const historyChanged = Number(cache.historyVersion || 0) !== getDataVersion();
  const upNextChanged = Number(cache.upNextVersion || 0) !== getUpNextVersion();
  const stale = historyChanged || upNextChanged || sourceVersion !== cache.sourceVersion || Date.now() - cache.builtAt >= UP_NEXT_TTL_MS;
  // Watch-state changes are safety-critical: serving the old snapshot while a
  // background rebuild runs can briefly put an already-watched episode back
  // in the rail. Provider-feed-only staleness keeps the old fast revalidate
  // behavior, but a history mismatch waits for the authoritative projection.
  if (historyChanged || upNextChanged) {
    if (allowStale) {
      // Always rebuild here: the throttle below is for provider-feed staleness,
      // and skipping it would leave an already-watched episode in the rail.
      queueBackgroundRebuild(build, { force: true });
      return publicSnapshot(cache, true, currentPublicSourceStatus());
    }
    return publicSnapshot(await buildAndStore(build));
  }
  if (!stale) return publicSnapshot(cache);
  if (revalidate) {
    queueBackgroundRebuild(build);
    return publicSnapshot(cache, true, currentPublicSourceStatus());
  }
  return publicSnapshot(await buildAndStore(build));
}
