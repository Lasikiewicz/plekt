// Bump when the projection's episode-order rules change so a persisted queue
// built by the previous rule cannot keep showing a later-season episode.
const CACHE_VERSION = 6;
const UP_NEXT_TTL_MS = 2 * 60 * 1000;
const REVALIDATE_MIN_INTERVAL_MS = 10 * 60 * 1000;
const MAX_ITEMS = 100;
const UP_NEXT_PROVIDERS = new Set(["plex", "emby", "jellyfin"]);
const CACHE_RENAME_RETRIES = 5;
const CACHE_RENAME_RETRY_MS = 20;

const cacheStates = new Map();

async function replaceCacheFile(tempFile, cacheFile) {
  for (let attempt = 0; ; attempt += 1) {
    try {
      await fs.rename(tempFile, cacheFile);
      return;
    } catch (error) {
      if (!(["EPERM", "EACCES", "EBUSY"].includes(error?.code)) || attempt >= CACHE_RENAME_RETRIES) {
        throw error;
      }
      await new Promise((resolve) => setTimeout(resolve, CACHE_RENAME_RETRY_MS));
    }
  }
}

function cacheState(dataDir = getActiveDataDir()) {
  const directory = path.resolve(dataDir);
  let state = cacheStates.get(directory);
  if (!state) {
    state = {
      directory,
      memoryCache: null,
      memoryMtimeMs: 0,
      writeChain: Promise.resolve(),
      buildInFlight: null,
      buildInFlightVersion: "",
      buildInFlightLabel: "",
      lastRevalidateAt: 0,
    };
    cacheStates.set(directory, state);
  }
  return state;
}

function queueAutomaticUpNextSync(reason) {
  void import("./upNextAutoSync.js")
    .then(({ requestUpNextAutoSync }) => requestUpNextAutoSync(reason))
    .catch((error) => console.error(`[up-next] Automatic sync request failed: ${error?.message || error}`));
}

function emptyCache() {
  return {
    version: CACHE_VERSION,
    builtAt: 0,
    sourceVersion: "",
    historyVersion: getDataVersion(),
    upNextVersion: getUpNextVersion(),
    items: [],
    sourceStatus: [],
  };
}

function normalizeCache(parsed) {
  if (Number(parsed?.version || 0) !== CACHE_VERSION) return emptyCache();
  const rawItems = Array.isArray(parsed?.items) ? parsed.items.slice(0, MAX_ITEMS) : [];
  // Only the episode identity repair is needed for the current regression.
  // Leave legacy movie/unknown rows byte-for-byte compatible until their next
  // normal projection refresh, since older movie ids were not always keys
  // generated by upNextIdentity.js.
  const mergeableItems = rawItems.filter((item) => item?.media_type === "episode");
  const passthroughItems = rawItems.filter((item) => item?.media_type !== "episode").map((item) => {
    const providerItems = Object.fromEntries(Object.entries(item?.provider_items || item?.providerItems || {})
      .map(([provider, ids]) => [String(provider || "").toLowerCase(), ids])
      .filter(([provider, ids]) => UP_NEXT_PROVIDERS.has(provider) && (Array.isArray(ids) ? ids.length : Boolean(ids))));
    const sanitized = { ...item, provider_items: providerItems, providerItems };
    if (sanitized?.media_type === "movie" && !sanitized.poster_url) {
      const canonical = getCanonicalPosterUrl({
        media_type: "movie",
        title: sanitized.title,
        tmdb_id: sanitized.tmdb_id,
        imdb_id: sanitized.imdb_id,
      });
      return canonical ? { ...sanitized, poster_url: canonical } : sanitized;
    }
    return sanitized;
  });
  return {
    version: CACHE_VERSION,
    builtAt: Number(parsed?.builtAt || 0),
    sourceVersion: String(parsed?.sourceVersion || ""),
    historyVersion: Number(parsed?.historyVersion || 0),
    upNextVersion: Number(parsed?.upNextVersion || getUpNextVersion()),
    // Older cache snapshots can contain the same resume twice under an
    // identity-bearing key and a title-only key. Normalize known media rows
    // while leaving legacy/diagnostic entries untouched. Re-sort with the
    // projection's own rule: appending the movies after the episodes moved a
    // part-watched movie to the end of the rail on every cached read.
    items: sortUpNextItems([...publicUpNextItems(mergeableItems), ...passthroughItems]).slice(0, MAX_ITEMS),
    sourceStatus: (Array.isArray(parsed?.sourceStatus) ? parsed.sourceStatus : [])
      .filter((feed) => UP_NEXT_PROVIDERS.has(String(feed?.provider || "").toLowerCase())),
  };
}

// What differed between two stored projections, for the build log: a rebuild
// that "changed" queues another provider push, so the log has to say whether a
// card appeared, left, moved, or only had a field (progress, ids) rewritten.
export function describeProjectionChange(previous = [], next = []) {
  const keyOf = (item) => String(item?.media_key || item?.id || "");
  const before = new Map((Array.isArray(previous) ? previous : []).map((item) => [keyOf(item), item]));
  const after = new Map((Array.isArray(next) ? next : []).map((item) => [keyOf(item), item]));
  const added = [...after.keys()].filter((key) => !before.has(key));
  const removed = [...before.keys()].filter((key) => !after.has(key));
  const fields = [];
  for (const [key, item] of after) {
    const old = before.get(key);
    if (!old) continue;
    const names = [...new Set([...Object.keys(old), ...Object.keys(item)])]
      .filter((name) => JSON.stringify(old[name]) !== JSON.stringify(item[name]));
    if (names.length) fields.push(`${key}: ${names.join(",")}`);
  }
  const keptOrder = [...after.keys()].filter((key) => before.has(key));
  const priorOrder = [...before.keys()].filter((key) => after.has(key));
  const reordered = JSON.stringify(keptOrder) !== JSON.stringify(priorOrder);
  const parts = [];
  if (added.length) parts.push(`added ${added.join(" ; ")}`);
  if (removed.length) parts.push(`removed ${removed.join(" ; ")}`);
  if (reordered) parts.push("reordered");
  if (fields.length) parts.push(`fields ${fields.slice(0, 5).join(" ; ")}`);
  return parts.join("; ") || "source status only";
}

async function readCache(state = cacheState()) {
  const cacheFile = path.join(state.directory, "up-next-cache.json");
  try {
    const stat = await fs.stat(cacheFile);
    if (state.memoryCache && state.memoryMtimeMs === stat.mtimeMs) return state.memoryCache;
    const parsed = JSON.parse(await fs.readFile(cacheFile, "utf8"));
    state.memoryCache = normalizeCache(parsed);
    state.memoryMtimeMs = stat.mtimeMs;
    return state.memoryCache;
  } catch (error) {
    if (error?.code !== "ENOENT") console.error("Failed to read Up Next cache", error);
    state.memoryCache = emptyCache();
    state.memoryMtimeMs = 0;
    return state.memoryCache;
  }
}

function normalizedItems(items) {
  return (Array.isArray(items) ? items : []).slice(0, MAX_ITEMS);
}

function comparableSourceStatus(status = []) {
  return (Array.isArray(status) ? status : []).map((feed) => ({
    provider: feed.provider,
    feed_kind: feed.feed_kind,
    status: feed.status,
    item_count: feed.item_count,
    complete: feed.complete,
    last_error: feed.last_error,
  }));
}

// `builtFrom` holds the versions current when the projection's build started.
// A queue mutation during the build (a drop, a dismissal) bumps them, and
// stamping the store-time versions would serve that older projection as
// current until the next rebuild. Such a projection keeps its start versions,
// so the next read sees the mismatch and waits for a fresh build.
async function storeCache(result, fallbackSourceVersion, builtFrom = null, state = cacheState()) {
  const projection = result && !Array.isArray(result) && typeof result === "object"
    ? result
    : { items: result };
  const nextItems = normalizedItems(projection.items);
  let stored;
  state.writeChain = state.writeChain.catch(() => {}).then(async () => {
    const current = await readCache(state);
    const nextSourceStatus = Array.isArray(projection.sourceStatus) ? projection.sourceStatus : [];
    const changed = !current.builtAt
      || JSON.stringify({ items: current.items, sourceStatus: comparableSourceStatus(current.sourceStatus) })
        !== JSON.stringify({ items: nextItems, sourceStatus: comparableSourceStatus(nextSourceStatus) });
    if (changed && current.builtAt) {
      console.log(`Up Next projection changed: ${describeProjectionChange(current.items, nextItems)}`);
    }
    const currentGlobalVersion = getUpNextVersion();
    const cachedVersion = Number(current.upNextVersion || 0);
    const outdated = Boolean(builtFrom)
      && (builtFrom.upNextVersion !== currentGlobalVersion || builtFrom.historyVersion !== getDataVersion());
    const historyVersion = outdated ? builtFrom.historyVersion : getDataVersion();
    const upNextVersion = outdated
      ? builtFrom.upNextVersion
      : changed
        ? (currentGlobalVersion > cachedVersion ? currentGlobalVersion : bumpUpNextVersion())
        : Math.max(cachedVersion || 1, currentGlobalVersion);
    const now = Date.now();
    const next = {
      version: CACHE_VERSION,
      builtAt: now,
      sourceVersion: String(projection.sourceVersion || fallbackSourceVersion || getUpNextFeedSourceVersion()),
      historyVersion,
      upNextVersion,
      items: nextItems,
      sourceStatus: nextSourceStatus,
    };
    const cacheFile = path.join(state.directory, "up-next-cache.json");
    const tempFile = `${cacheFile}.${process.pid}.${Date.now()}.${Math.random().toString(36).slice(2)}.tmp`;
    await fs.mkdir(state.directory, { recursive: true });
    await fs.writeFile(tempFile, JSON.stringify(next), "utf8");
    try {
      await replaceCacheFile(tempFile, cacheFile);
    } catch (error) {
      await fs.rm(tempFile, { force: true }).catch(() => {});
      throw error;
    }
    // Keep serving exactly what was built. Forcing a re-read ran our own write
    // back through normalizeCache, so the next rebuild never compared equal and
    // every rebuild bumped the Up Next version. Another process's later write
    // still changes the mtime and is picked up.
    state.memoryCache = next;
    state.memoryMtimeMs = await fs.stat(cacheFile).then((stat) => stat.mtimeMs, () => 0);
    stored = { ...next, changed };
  });
  await state.writeChain;
  if (stored?.changed) queueAutomaticUpNextSync("Up Next projection changed");
  return stored;
}

// One line per build decision, so the diagnostic log shows which caller asked
// for each build, why the served snapshot was not current, and which write moved
// the history generation (plan/archive/up-next-build-speed/summary.md, step 2). `cause` is
// supplied by the reader; `cached` is the snapshot generation it found.
export function describeUpNextBuildRequest(trigger, cause = "", cached = null) {
  const parts = [String(trigger || "unattributed")];
  if (cause) parts.push(cause);
  const history = getDataVersion();
  const queue = getUpNextVersion();
  if (cached && Number(cached.historyVersion || 0) !== history) {
    parts.push(`history v${cached.historyVersion || 0} to v${history} (${dataVersionTrigger(history)})`);
  }
  if (cached && Number(cached.upNextVersion || 0) !== queue) {
    parts.push(`queue v${cached.upNextVersion || 0} to v${queue}`);
  }
  return parts.join("; ");
}

function logBuildDecision(kind, label) {
  console.log(`Up Next build ${kind}: ${label}`);
}

function buildAndStore(build, state = cacheState(), label = "unattributed") {
  // getDataVersion() re-reads the shared generation at most every 500 ms. A
  // canonical write that landed just before this build (an Emby unplayed echo
  // during a removal) is read by the build but, with the lagging version,
  // stamped as newer than the snapshot once the poll adopts it, which cost a
  // second build per removal. Read the shared generation fresh instead.
  const builtFrom = { upNextVersion: getUpNextVersion(), historyVersion: refreshDataVersion() };
  const requestedVersion = `${builtFrom.upNextVersion}:${builtFrom.historyVersion}`;
  if (state.buildInFlight) {
    // A manual queue change can arrive while a projection is already being
    // built. Do not let the caller receive that older projection and stamp it
    // as current; wait for it to finish, then build against the new queue
    // generation.
    if (state.buildInFlightVersion !== requestedVersion) {
      logBuildDecision("chained", `${label}; behind ${state.buildInFlightLabel} (generation moved to ${requestedVersion})`);
      return state.buildInFlight.then(() => buildAndStore(build, state, label));
    }
    logBuildDecision("joined", `${label}; shares ${state.buildInFlightLabel}`);
    return state.buildInFlight;
  }
  state.buildInFlightVersion = requestedVersion;
  state.buildInFlightLabel = label;
  logBuildDecision("started", label);
  state.buildInFlight = Promise.resolve()
    .then(() => build({ trigger: label }))
    .then((result) => storeCache(result, getUpNextFeedSourceVersion(), builtFrom, state))
    .finally(() => {
      state.buildInFlight = null;
      state.buildInFlightVersion = "";
      state.buildInFlightLabel = "";
    });
  return state.buildInFlight;
}

// Complete an explicit queue mutation before acknowledging it to another device.
// Provider feed refreshes remain background work; this projects canonical state.
export async function refreshUpNextAfterMutation(mediaConfig, reason) {
  const { invalidateHistoryDerivedCaches } = await import("./dataRepo.js");
  const { buildUpNextProjection } = await import("./upNextService.js");
  await invalidateHistoryDerivedCaches(reason);
  return buildAndStore((ctx) => buildUpNextProjection({ mediaConfig, ...ctx }), cacheState(), `mutation ${reason}`);
}

function publicSnapshot(cache, stale = false, sourceStatus = cache.sourceStatus) {
  return {
    items: cache.items,
    builtAt: cache.builtAt,
    historyVersion: cache.historyVersion,
    upNextVersion: cache.upNextVersion,
    sourceVersion: cache.sourceVersion,
    sourceStatus,
    stale,
  };
}

function currentPublicSourceStatus() {
  return listUpNextProviderFeedStates()
    .filter((feed) => UP_NEXT_PROVIDERS.has(String(feed?.provider || "").toLowerCase()))
    .map((feed) => {
      const publicFeed = { ...feed };
      delete publicFeed.cursor;
      return publicFeed;
    });
}

// `force` skips the provider-feed throttle. It is used when the served snapshot
// predates the latest watch history, where a rebuild must always follow.
function queueBackgroundRebuild(build, { force = false, label = "background" } = {}, state = cacheState()) {
  if (!force && Date.now() - state.lastRevalidateAt < REVALIDATE_MIN_INTERVAL_MS) return false;
  state.lastRevalidateAt = Date.now();
  // Start on a later timer turn rather than a promise microtask. A stale
  // dashboard response should finish before the provider-backed projection
  // can begin its synchronous cache assembly and compete with sibling APIs.
  const timer = setTimeout(() => {
    buildAndStore(build, state, label)
      .then((result) => {
        console.log(`Up Next cache background rebuild complete: ${result.items.length} item${result.items.length === 1 ? "" : "s"}${result.changed ? ", cache updated" : ", unchanged"}.`);
      })
      .catch((error) => {
        console.warn(`Up Next cache background rebuild failed: ${error.message}`);
      });
  }, 0);
  timer.unref?.();
  return true;
}

// Return a warm snapshot immediately when possible. `revalidate` is used by
// the dashboard: stale data remains visible while one deduplicated rebuild
// runs behind the request. Explicit `refresh` keeps the existing manual retry
// semantics and waits for a fresh snapshot.
export async function getUpNextCacheSnapshot(build, {
  refresh = false,
  revalidate = false,
  allowStale = false,
  trigger = "snapshot",
} = {}) {
  const state = cacheState();
  if (refresh) return publicSnapshot(await buildAndStore(build, state, describeUpNextBuildRequest(trigger, "explicit refresh")));

  const cache = await readCache(state);
  if (!cache.builtAt) {
    const label = describeUpNextBuildRequest(trigger, "no cached snapshot");
    if (allowStale) {
      queueBackgroundRebuild(build, { force: true, label: `background ${label}` }, state);
      return publicSnapshot(cache, true, currentPublicSourceStatus());
    }
    return publicSnapshot(await buildAndStore(build, state, label));
  }

  const sourceVersion = getUpNextFeedSourceVersion();
  const historyChanged = Number(cache.historyVersion || 0) !== getDataVersion();
  const upNextChanged = Number(cache.upNextVersion || 0) !== getUpNextVersion();
  const stale = historyChanged || upNextChanged || sourceVersion !== cache.sourceVersion || Date.now() - cache.builtAt >= UP_NEXT_TTL_MS;
  // Watch-state changes are safety-critical: serving the old snapshot while a
  // background rebuild runs can briefly put an already-watched episode back
  // in the rail. Provider-feed-only staleness keeps the old fast revalidate
  // behavior, but a history mismatch waits for the authoritative projection.
  if (historyChanged || upNextChanged) {
    const label = describeUpNextBuildRequest(trigger, "snapshot out of date", cache);
    if (allowStale) {
      // Always rebuild here: the throttle below is for provider-feed staleness,
      // and skipping it would leave an already-watched episode in the rail.
      queueBackgroundRebuild(build, { force: true, label: `background ${label}` }, state);
      return publicSnapshot(cache, true, currentPublicSourceStatus());
    }
    return publicSnapshot(await buildAndStore(build, state, label));
  }
  if (!stale) return publicSnapshot(cache);
  const feedLabel = describeUpNextBuildRequest(trigger, sourceVersion !== cache.sourceVersion ? "provider feeds changed" : "snapshot older than its time limit");
  if (revalidate) {
    queueBackgroundRebuild(build, { label: `background ${feedLabel}` }, state);
    return publicSnapshot(cache, true, currentPublicSourceStatus());
  }
  return publicSnapshot(await buildAndStore(build, state, feedLabel));
}
